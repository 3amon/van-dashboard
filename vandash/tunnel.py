"""Cloudflare tunnel supervisor — reach the van without being on its LAN.

The Pi lives behind whatever wifi the van found, so inbound connections are
hopeless. cloudflared dials OUT to Cloudflare and exposes:

    https://van-live.example.net -> this dashboard (localhost:8080), direct
    ssh-van.example.net          -> sshd, via `cloudflared access ssh` client

(van.example.net itself points at an always-on mirror host, which
the uplink keeps fed; see uplink.py. The old ingress rule is kept so the
hostname still works if DNS is ever pointed back here.)

It rides inside the dashboard process (started from server.py) because the
git auto-updater restarts van-dashboard.service on every deploy — the only
code-execution path we have while the van is off somewhere. No root, no
inbound ports; the arm64 binary self-installs to ~/.local/bin on first run.

Enabled only where the deploy updater timer is installed (i.e. the real Pi),
or with VANDASH_TUNNEL=1 for testing. To kill remote access: delete
deploy/tunnel/credentials.json from the repo, or delete the "vandash" tunnel
in Cloudflare.
"""

from __future__ import annotations

import asyncio
import logging
import os
import platform
import shutil
import stat
import urllib.request
from pathlib import Path

logger = logging.getLogger(__name__)

TUNNEL_ID = "00000000-0000-4000-8000-000000000000"
PI_MARKER = Path("/etc/systemd/system/van-dashboard-update.timer")
DOWNLOAD_ARCH = {"aarch64": "arm64", "arm64": "arm64", "x86_64": "amd64", "armv7l": "arm"}

CONFIG_TEMPLATE = """\
# Generated by vandash.tunnel at startup — do not edit.
tunnel: {tunnel_id}
credentials-file: {credentials}
no-autoupdate: true
ingress:
  - hostname: van-live.example.net
    service: http://localhost:{port}
  - hostname: van.example.net
    service: http://localhost:{port}
  - hostname: ssh-van.example.net
    service: ssh://localhost:22
  - service: http_status:404
"""


def credentials_path(project_root: Path) -> Path:
    return project_root / "deploy" / "tunnel" / "credentials.json"


def enabled(project_root: Path) -> bool:
    if not credentials_path(project_root).is_file():
        return False
    return bool(os.environ.get("VANDASH_TUNNEL")) or PI_MARKER.is_file()


def _find_or_install_binary() -> Path:
    found = shutil.which("cloudflared")
    if found:
        return Path(found)
    local = Path.home() / ".local" / "bin" / "cloudflared"
    if local.is_file():
        return local
    arch = DOWNLOAD_ARCH.get(platform.machine())
    if arch is None:
        raise RuntimeError(f"no cloudflared build for {platform.machine()}")
    url = ("https://github.com/cloudflare/cloudflared/releases/latest/download/"
           f"cloudflared-linux-{arch}")
    logger.info("Downloading cloudflared (%s) ...", arch)
    local.parent.mkdir(parents=True, exist_ok=True)
    partial = local.with_suffix(".part")
    with urllib.request.urlopen(url, timeout=120) as response, open(partial, "wb") as f:
        shutil.copyfileobj(response, f)
    partial.chmod(partial.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    partial.rename(local)
    logger.info("Installed cloudflared to %s", local)
    return local


async def _supervise(project_root: Path, port: int) -> None:
    try:
        binary = await asyncio.to_thread(_find_or_install_binary)
    except Exception:
        logger.exception("cloudflared unavailable — no remote access this run")
        return

    data_dir = project_root / "data"
    data_dir.mkdir(exist_ok=True)
    config = data_dir / "tunnel-config.yml"
    config.write_text(CONFIG_TEMPLATE.format(
        tunnel_id=TUNNEL_ID,
        credentials=credentials_path(project_root),
        port=port,
    ))
    log_path = data_dir / "tunnel.log"

    backoff = 15.0
    while True:
        started = asyncio.get_event_loop().time()
        # Truncate per attempt: cloudflared is chatty and the SD card is small.
        with open(log_path, "wb") as log_file:
            process = await asyncio.create_subprocess_exec(
                str(binary), "--config", str(config), "tunnel", "run",
                stdout=log_file, stderr=asyncio.subprocess.STDOUT,
            )
            logger.info("cloudflared running (pid %d)", process.pid)
            try:
                code = await process.wait()
            except asyncio.CancelledError:
                process.terminate()
                try:
                    await asyncio.wait_for(process.wait(), timeout=10)
                except asyncio.TimeoutError:
                    process.kill()
                raise
        uptime = asyncio.get_event_loop().time() - started
        backoff = 15.0 if uptime > 120 else min(backoff * 2, 300.0)
        logger.warning("cloudflared exited %s after %.0fs — retrying in %.0fs",
                       code, uptime, backoff)
        await asyncio.sleep(backoff)


def maybe_start(project_root: Path, port: int = 8080) -> asyncio.Task | None:
    """Start the tunnel supervisor task if this machine should run one."""
    if not enabled(project_root):
        return None
    logger.info("Remote-access tunnel enabled (van.example.net)")
    return asyncio.create_task(_supervise(project_root, port), name="tunnel")
